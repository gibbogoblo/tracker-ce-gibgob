#!/usr/bin/env python3
# LILITRON voice: renders the syllables with MBROLA (us1, female) the "tiny" way
# (sung 5 semitones low, then sped up: a smaller mouth), flat in pitch, and
# finds a seamless loop in each held vowel. Writes:
#   LILITRON.wav      one mono 16-bit file with every syllable at two pitches
#   lilitron_table.h  where each one starts and loops (the engine reads it)
# Needs: mbrola + mbrola-us1, sox, numpy.   python3 make_voice.py <out dir>
import math, os, subprocess, sys, tempfile, wave
import numpy as np

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
VOICE = '/usr/share/mbrola/us1/us1'
SR = 32000
SHIFT = 5          # semitones sung lower, then sped up
LOOP_MS = 110      # the looped part of each vowel
XFADE_MS = 25

# name, consonants (phone, ms), vowel phone, closing phone and its share of the held part
SYLLABLES = [
    ('tah', [('t_h', 70)], 'A', None),
    ('dee', [('d', 55)], 'i', None),
    ('umm', [], 'V', ('m', 0.6)),
    ('lee', [('l', 80)], 'i', None),
    ('aah', [], 'A', None),
    ('bah', [('b', 60)], 'A', None),
    ('so',  [('s', 110)], '@U', None),
    ('lah', [('l', 80)], 'A', None),
    ('nyaa', [('n', 70), ('j', 70)], '{', None),  # the cat
]
ROOTS = [60, 72]   # C4, C5 (the cat: a fifth up, G4 / G5)

def hz(note):
    return 440.0 * 2 ** ((note - 69) / 12)

def render(name, root):
    _, cons, vowel, close = next(s for s in SYLLABLES if s[0] == name)
    f0 = hz(root - SHIFT)
    held = 520
    lines = ['_ 30']
    for ph, d in cons:
        lines.append(f'{ph} {d} 0 {f0:.1f} 100 {f0:.1f}')
    if close:
        v = int(held * (1 - close[1]))
        lines.append(f'{vowel} {v} 0 {f0:.1f} 100 {f0:.1f}')
        lines.append(f'{close[0]} {held - v} 0 {f0:.1f} 100 {f0:.1f}')
    else:
        lines.append(f'{vowel} {held} 0 {f0:.1f} 100 {f0:.1f}')
    lines.append('_ 30')
    with tempfile.TemporaryDirectory() as d:
        pho, raw, fast = d + '/s.pho', d + '/s.wav', d + '/f.wav'
        open(pho, 'w').write('\n'.join(lines) + '\n')
        subprocess.run(['mbrola', '-e', VOICE, pho, raw], check=True, capture_output=True)
        subprocess.run(['sox', raw, fast, 'speed', str(2 ** (SHIFT / 12)), 'rate', '-v', str(SR)], check=True)
        w = wave.open(fast)
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64) / 32768
    return x, len(cons) > 0

def make(name, root):
    x, _ = render(name, root)
    env = np.abs(x)
    # start: the first sound
    on = np.where(env > 0.01)[0]
    first, last = on[0], on[-1]
    x = x[max(0, first - 32):last]
    # the loop: whole pitch periods near the end of the held part
    period = SR / hz(root)
    n = max(1, round(LOOP_MS / 1000 * SR / period))
    length = int(round(n * period))
    loop_end = len(x) - int(0.06 * SR)          # clear of the fade at the end
    loop_start = loop_end - length
    xf = int(XFADE_MS / 1000 * SR)
    assert loop_start - xf > int(0.08 * SR), name
    # crossfade: the end of the loop blends into what comes before its start,
    # so jumping from loop_end back to loop_start is seamless
    w = np.linspace(0, 1, xf)
    a = x[loop_end - xf:loop_end].copy()
    b = x[loop_start - xf:loop_start]
    x[loop_end - xf:loop_end] = a * (1 - w) + b * w
    x = x[:loop_end]
    # the same loudness for every syllable (measured on the loop)
    rms = np.sqrt(np.mean(x[loop_start:loop_end] ** 2)) + 1e-9
    x = x * (0.16 / rms)
    return x, loop_start, loop_end

def main():
    pieces, table, pos = [], [], 0
    for root in ROOTS:
        for name, *_ in SYLLABLES:
            r = root + (7 if name == 'nyaa' else 0)
            x, ls, le = make(name, r)
            pieces.append(x)
            table.append((name, r, pos, pos + ls, pos + le))
            pos += len(x) + 64
            pieces.append(np.zeros(64))
    data = np.concatenate(pieces)
    peak = np.abs(data).max()
    if peak > 0.98:
        data *= 0.98 / peak
    pcm = (data * 32767).astype(np.int16)
    w = wave.open(os.path.join(OUT, 'LILITRON.wav'), 'w')
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes(pcm.tobytes()); w.close()
    with open(os.path.join(OUT, 'lilitron_table.h'), 'w') as f:
        f.write('// Generated by make_voice.py: where each syllable sits in LILITRON.wav\n#pragma once\n#include <cstdint>\n\n')
        f.write('namespace lili\n{\n')
        f.write(f'constexpr int kSampleRate = {SR};\nconstexpr uint32_t kTotalFrames = {len(pcm)};\n')
        f.write(f'constexpr int kSyllables = {len(SYLLABLES)}; // the last one is the cat\n')
        f.write(f'constexpr int kRoots = {len(ROOTS)};\n')
        f.write('struct Segment\n{\n    uint8_t root; // MIDI note it was sung at\n    uint32_t start, loopStart, loopEnd;\n};\n')
        f.write('constexpr const char* kNames[kSyllables] = { ' + ', '.join(f'"{s[0]}"' for s in SYLLABLES) + ' };\n')
        f.write('constexpr Segment kSegments[kRoots][kSyllables] = {\n')
        for i, root in enumerate(ROOTS):
            f.write('    {\n')
            for name, r, s, ls, le in table[i * len(SYLLABLES):(i + 1) * len(SYLLABLES)]:
                f.write(f'        {{ {r}, {s}, {ls}, {le} }}, // {name}\n')
            f.write('    },\n')
        f.write('};\n} // namespace lili\n')
    print(f'{len(pcm)} frames, {len(pcm) / SR:.2f} s, {len(pcm) * 2 // 1024} KB')

main()
