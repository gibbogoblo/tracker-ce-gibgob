#!/usr/bin/env python3
# GibGob OS PERC: makes PercKits.h from
#  - the LXR-02 firmware (Erica Synths, github.com/erica-synths/lxr-desktop-app, GPL-3.0-only): the
#    sound parameter numbers (Core/Inc/Parameters.h, the front panel's list, which is the .SND layout) and the modulation targets
#    (Core/Src/menu/Cc2Text.c, modTargets), and
#  - the LXR-02 kits in ../kits (.SND: 8 name bytes, then sound parameters 0..246), the factory kits and
#    Hrtl's DLC and UNTZ packs, distributed with Erica Synths' permission (see ../kits/README.md).
# Usage: gen_perc_kits.py LXR_DESKTOP_APP_DIR [OUT]
import os, re, sys

lxr = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'PercKits.h')

# ---- the parameter numbers (the enum, aliases included) ----
src = open(os.path.join(lxr, 'Core/Inc/Parameters.h')).read()  # the front panel's list: the .SND layout
body = src[src.index('enum ParamEnums'):]
body = body[body.index('{') + 1:body.index('};')]
body = re.sub(r'//[^\n]*', '', body)
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
par = {}
nxt = 0
for item in body.split(','):
    item = item.strip()
    if not item:
        continue
    if '=' in item:
        name, val = [x.strip() for x in item.split('=', 1)]
        v = par[val] if val in par else int(val, 0)
    else:
        name, v = item, nxt
    par[name] = v
    nxt = v + 1
END = par['END_OF_SOUND_PARAMETERS']
assert END == 247, END

# ---- the modulation targets (index -> parameter) ----
cc = open(os.path.join(lxr, 'Core/Src/menu/Cc2Text.c')).read()
mt = cc[cc.index('const ModTarg modTargets[]'):]
mt = mt[mt.index('{') + 1:mt.index('};')]
mt = re.sub(r'//[^\n]*', '', mt)
targets = [par[m] for m in re.findall(r'\{\s*TEXT_[A-Z0-9_]+\s*,\s*(PAR_[A-Z0-9_]+)\s*\}', mt)]

# ---- the kits ----
kits = []
for bank in ('factory', 'hrtl-dlc', 'hrtl-untz'):
    d = os.path.join(here, '..', 'kits', bank)
    for f in sorted(os.listdir(d)):
        if not f.upper().endswith('.SND'):
            continue
        b = open(os.path.join(d, f), 'rb').read()
        assert len(b) == 8 + END, (f, len(b))
        name = b[:8].decode('latin1').rstrip(' \0')
        kits.append((bank, name, b[8:]))

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

with open(out, 'w') as o:
    o.write('// SPDX-License-Identifier: GPL-3.0-only\n')
    o.write('// GibGob OS PERC: generated by tools/gen_perc_kits.py; do not edit.\n')
    o.write('// The parameter numbers and modulation targets are the LXR-02 firmware\'s (Erica Synths,\n')
    o.write('// GPL-3.0-only). The kits are the LXR-02\'s factory kits and Hrtl\'s DLC and UNTZ packs,\n')
    o.write('// distributed with Erica Synths\' permission (kits/README.md).\n')
    o.write('#pragma once\n#include <stdint.h>\n\nnamespace gibgob\n{\nnamespace perc\n{\nnamespace lxr\n{\n')
    o.write('enum Par : uint16_t\n{\n')
    for name, v in sorted(par.items(), key=lambda kv: (kv[1], kv[0])):
        if v <= END:
            o.write('    %s = %d,\n' % (name, v))
    o.write('};\n\n')
    o.write('// the LXR\'s modulation targets (an LFO\'s or the velocity\'s target in a kit is an index here)\n')
    o.write('static constexpr int kModTargetCount = %d;\n' % len(targets))
    o.write('static const uint16_t kModTargetPar[kModTargetCount] = { %s };\n\n' % ', '.join(map(str, targets)))
    o.write('static constexpr int kKitParams = %d;\n' % END)
    o.write('static constexpr int kKitCount = %d;\n' % len(kits))
    o.write('static constexpr int kFactoryKits = %d;\n' % sum(1 for k in kits if k[0] == 'factory'))
    o.write('static const char* const kKitName[kKitCount] = {\n')
    for k in kits:
        o.write('    %s,\n' % cstr(k[1]))
    o.write('};\n')
    o.write('static const uint8_t kKit[kKitCount][kKitParams] = {\n')
    for k in kits:
        o.write('    { %s },\n' % ', '.join(map(str, k[2])))
    o.write('};\n\n} // namespace lxr\n} // namespace perc\n} // namespace gibgob\n')
print('wrote', out, len(kits), 'kits,', len(targets), 'targets')
